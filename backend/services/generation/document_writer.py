"""
Write generated content to files in supported formats.
"""

from __future__ import annotations

import json
import re
import zipfile
from pathlib import Path

from services.generation.format_registry import default_basename, mime_for_extension


def _strip_code_fences(text: str) -> str:
    """Remove markdown code fences if the model wrapped output."""
    stripped = text.strip()
    fence = re.match(r"^```(?:\w+)?\s*([\s\S]*?)\s*```$", stripped)
    if fence:
        return fence.group(1).strip()
    return stripped


def _write_text(path: Path, content: str) -> None:
    path.write_text(content, encoding="utf-8")


def _write_pdf(path: Path, content: str, title: str = "Document") -> None:
    try:
        from reportlab.lib.pagesizes import letter
        from reportlab.pdfgen import canvas

        c = canvas.Canvas(str(path), pagesize=letter)
        width, height = letter
        y = height - 72
        c.setFont("Helvetica-Bold", 14)
        c.drawString(72, y, title[:80])
        y -= 24
        c.setFont("Helvetica", 11)
        for line in content.splitlines():
            if y < 72:
                c.showPage()
                y = height - 72
                c.setFont("Helvetica", 11)
            c.drawString(72, y, line[:100])
            y -= 14
        c.save()
    except ImportError:
        _write_text(path.with_suffix(".txt"), content)


def _write_docx(path: Path, content: str, title: str = "Document") -> None:
    try:
        from docx import Document

        doc = Document()
        doc.add_heading(title, level=1)
        for para in content.split("\n\n"):
            if para.strip():
                doc.add_paragraph(para.strip())
        doc.save(str(path))
    except ImportError:
        _write_text(path.with_suffix(".txt"), content)


def _write_xlsx(path: Path, content: str, title: str = "Spreadsheet") -> None:
    try:
        from openpyxl import Workbook

        wb = Workbook()
        ws = wb.active
        ws.title = title[:31] or "Sheet1"
        for row_idx, line in enumerate(content.splitlines(), start=1):
            cells = [c.strip() for c in line.split("\t")]
            if len(cells) == 1 and "," in line:
                cells = [c.strip() for c in line.split(",")]
            for col_idx, cell in enumerate(cells, start=1):
                ws.cell(row=row_idx, column=col_idx, value=cell)
        wb.save(str(path))
    except ImportError:
        _write_text(path.with_suffix(".csv"), content)


def _write_pptx(path: Path, content: str, title: str = "Presentation") -> None:
    try:
        from pptx import Presentation

        prs = Presentation()
        # Title slide
        slide = prs.slides.add_slide(prs.slide_layouts[0])
        slide.shapes.title.text = title
        slide.placeholders[1].text = "Generated by TokenMaxx"

        sections = [s.strip() for s in re.split(r"\n#{1,3}\s+", content) if s.strip()]
        if not sections:
            sections = [p.strip() for p in content.split("\n\n") if p.strip()]

        for section in sections[:20]:
            slide = prs.slides.add_slide(prs.slide_layouts[1])
            lines = section.split("\n", 1)
            slide.shapes.title.text = lines[0][:100]
            if len(lines) > 1:
                slide.placeholders[1].text = lines[1][:2000]
        prs.save(str(path))
    except ImportError:
        _write_text(path.with_suffix(".txt"), content)


def _parse_project_files(content: str) -> dict[str, str]:
    """
    Parse multi-file project output.

    Expected format:
    === path/to/file.py ===
    content
  """
    files: dict[str, str] = {}
    pattern = re.compile(r"^===\s*(.+?)\s*===\s*$", re.MULTILINE)
    parts = pattern.split(content)
    if len(parts) > 1:
        i = 1
        while i < len(parts) - 1:
            filepath = parts[i].strip().lstrip("/")
            file_content = parts[i + 1].strip()
            if filepath and file_content:
                files[filepath] = _strip_code_fences(file_content)
            i += 2
    if not files:
        files["README.md"] = content.strip()
    return files


def write_document_file(
    path: Path,
    content: str,
    file_type: str,
    *,
    title: str | None = None,
    is_project: bool = False,
) -> tuple[Path, str, int]:
    """
    Write content to path according to file_type.

    Returns (final_path, mime_type, file_count).
    """
    ext = file_type.lower().lstrip(".")
    doc_title = title or default_basename(ext)

    if is_project or ext == "zip":
        zip_path = path if path.suffix == ".zip" else path.with_suffix(".zip")
        files = _parse_project_files(content)
        with zipfile.ZipFile(zip_path, "w", zipfile.ZIP_DEFLATED) as zf:
            for rel_path, file_content in files.items():
                zf.writestr(rel_path, file_content)
        return zip_path, mime_for_extension("zip"), len(files)

    clean = _strip_code_fences(content)

    if ext == "pdf":
        _write_pdf(path, clean, doc_title)
    elif ext == "docx":
        _write_docx(path, clean, doc_title)
    elif ext == "xlsx":
        _write_xlsx(path, clean, doc_title)
    elif ext == "pptx":
        _write_pptx(path, clean, doc_title)
    elif ext == "json":
        try:
            parsed = json.loads(clean)
            path.write_text(json.dumps(parsed, indent=2), encoding="utf-8")
        except json.JSONDecodeError:
            _write_text(path, clean)
    elif ext == "dockerfile":
        final = path.parent / "Dockerfile"
        _write_text(final, clean)
        return final, mime_for_extension("dockerfile"), 1
    else:
        if not path.suffix:
            path = path.with_suffix(f".{ext}")
        _write_text(path, clean)

    return path, mime_for_extension(ext), 1
